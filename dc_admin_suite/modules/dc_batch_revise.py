FILE_INPUT_SEL = 'input[type="file"][name="batch_revise"]'
SUBMIT_SEL = 'input[type="submit"][name="upload"]'


def _dismiss_alert(driver) -> str:
    """Accept a JS alert if one is showing (the page's validateFileType
    rejects non-.xls names with an alert AND clears the file input).
    Returns the alert text, or "" when no alert was present."""
    try:
        alert = driver.switch_to.alert
        text = alert.text or "page validator alert"
        alert.accept()
        return text
    except Exception:
        return ""


def upload_worker(session, out_dir, files, regen):
    """files = [{"path","ctx","part","name"}, ...] already validated by
    /api/start; regen = fire x_regenerate=1 per structure afterwards."""
    base_url = session["base_url"].rstrip("/")

    # Group by structure, parts in order; per-structure sequencing matters
    # (part 1 before part 2), structure order is alphabetical.
    groups = {}
    for f in files:
        groups.setdefault(f["ctx"], []).append(f)
    for g in groups.values():
        g.sort(key=lambda f: (f["part"], f["name"]))
    ordered_ctx = sorted(groups)

    total = len(files) + (len(ordered_ctx) if regen else 0)
    results = []   # (order, ctx, filename, status, timestr, url)
    primary = _primary_rgb(session)
    ok_files = warn_files = 0

    def finish_log(partial_reason=None):
        if not results:
            return None
        set_state(phase="writing")
        set_progress(len(results), total, "Writing upload log…")
        suffix = "_PARTIAL" if partial_reason else ""
        fname = "DC_BatchRevise_UploadLog_{}{}.xlsx".format(
            time.strftime("%Y%m%d_%H%M%S"), suffix)
        path = os.path.join(out_dir, fname)
        write_upload_workbook(path, results, primary)
        log("Wrote {}{}".format(
            path, " ({})".format(partial_reason) if partial_reason else ""))
        set_state(last_file=path)
        return path

    def expired(ctx):
        """Shared session-expired exit: partial log + error state."""
        finish_log("session expired; {} step(s) done".format(len(results)))
        fail("Digital Commons session expired at '{}'. Log in inside the "
             "debug Chrome window and start the upload again — the partial "
             "log shows what was already submitted.".format(ctx))

    try:
        set_state(phase="starting", summary="", last_file=None,
                  run_dir=None, paused=False)
        driver = _attach_or_fail(session)
        if driver is None:
            return

        set_state(phase="uploading")
        log("Uploading {} file(s) to {} structure(s){}…".format(
            len(files), len(ordered_ctx),
            " + regeneration" if regen else ""))

        step = 0
        t0 = time.time()
        for ctx in ordered_ctx:
            page_url = batch_revise_url(base_url, ctx)
            submitted_here = 0

            for f in groups[ctx]:
                check_pause_stop()
                step += 1
                timestr = time.strftime("%H:%M:%S")

                # Fresh page per file — each submit navigates away, and a
                # fresh form is the only state we can trust.
                driver.get(page_url)
                time.sleep(1.5)
                if looks_like_login_page(driver.page_source,
                                         driver.current_url):
                    results.append((step, ctx, f["name"], "LOGIN REQUIRED",
                                    timestr, page_url))
                    return expired(ctx)

                try:
                    file_input = driver.find_element(
                        "css selector", FILE_INPUT_SEL)
                except Exception:
                    results.append((step, ctx, f["name"],
                                    "No upload form on page", timestr,
                                    page_url))
                    warn_files += 1
                    log("WARNING: no upload form at '{}' — skipped {}."
                        .format(ctx, f["name"]))
                    continue

                try:
                    file_input.send_keys(os.path.abspath(f["path"]))
                    alert_text = _dismiss_alert(driver)
                    if alert_text:
                        results.append((step, ctx, f["name"],
                                        "Rejected by page validator: " +
                                        alert_text, timestr, page_url))
                        warn_files += 1
                        log("WARNING: page rejected {} — {}".format(
                            f["name"], alert_text))
                        continue
                    driver.find_element("css selector", SUBMIT_SEL).click()
                except Exception as e:
                    results.append((step, ctx, f["name"],
                                    "Submit failed: " + e.__class__.__name__,
                                    timestr, page_url))
                    warn_files += 1
                    log("WARNING: submit failed for {} ({})."
                        .format(f["name"], e.__class__.__name__))
                    continue

                time.sleep(UPLOAD_SETTLE)
                _dismiss_alert(driver)   # belt-and-braces: late alert
                html = driver.page_source
                if looks_like_login_page(html, driver.current_url):
                    results.append((step, ctx, f["name"], "LOGIN REQUIRED",
                                    timestr, page_url))
                    return expired(ctx)

                # The response page is undocumented; landing back on a page
                # with the history table / upload form means the POST was
                # taken. Anything else is submitted-but-verify.
                if 'id="batch-history"' in html or "batch_revise" in html:
                    status = "Submitted"
                else:
                    status = ("Submitted (unrecognized response page — "
                              "verify in DC)")
                    log("NOTE: unrecognized response page after {} — "
                        "verify in DC.".format(f["name"]))
                results.append((step, ctx, f["name"], status, timestr,
                                page_url))
                submitted_here += 1
                ok_files += 1
                set_progress(step, total, "{} · {} · {}".format(
                    ctx, f["name"], eta_text(step, total, t0)))

            # ---- optional per-structure regeneration ----------------------
            if regen:
                check_pause_stop()
                step += 1
                timestr = time.strftime("%H:%M:%S")
                r_url = regen_url(base_url, ctx)
                if submitted_here:
                    driver.get(r_url)
                    time.sleep(0.8)
                    if looks_like_login_page(driver.page_source,
                                             driver.current_url):
                        results.append((step, ctx, "—", "LOGIN REQUIRED",
                                        timestr, r_url))
                        return expired(ctx)
                    results.append((step, ctx, "—", "Regenerated",
                                    timestr, r_url))
                else:
                    results.append((step, ctx, "—",
                                    "Regeneration skipped (nothing "
                                    "submitted)", timestr, r_url))
                set_progress(step, total, "{} · regenerate · {}".format(
                    ctx, eta_text(step, total, t0)))

        path = finish_log()
        set_progress(total, total, "Done")
        summary = "{} of {} file(s) submitted".format(ok_files, len(files))
        if warn_files:
            summary += " · {} problem(s), see log".format(warn_files)
        if regen:
            summary += " · regeneration requested per structure"
        summary += (". DC imports revisions through its batch queue — "
                    "check Batch status in DC for content-level results.")
        if path:
            summary += " Log: " + os.path.basename(path)
        set_state(phase="done", summary=summary, paused=False)
    except StopRequested:
        log("Stop requested — {} step(s) done.".format(len(results)))
        path = finish_log("stopped early; {} step(s) done"
                          .format(len(results)))
        if path:
            set_state(phase="done", paused=False,
                      summary="Stopped early ({} of {} file(s) submitted). "
                              "Partial upload log: {}".format(
                                  ok_files, len(files),
                                  os.path.basename(path)))
        else:
            set_state(phase="idle", paused=False)
            set_progress(0, 0, "")
            log("Stopped before any file was submitted.")
    except Exception as e:
        finish_log("unexpected error; {} step(s) done".format(len(results)))
        fail("Unexpected error: {}: {}".format(e.__class__.__name__, e))


