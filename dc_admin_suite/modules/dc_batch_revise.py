# Cookie-based file fetch — downloads go to the USER'S chosen folder, not
# Chrome's download directory. Cookies come from the attached debug Chrome
# (the driver must currently be on a page of the DC domain).
# ---------------------------------------------------------------------------
def fetch_report_bytes(driver, url: str, timeout: int = 120) -> bytes:
    """GET `url` with the driver's cookies and return the raw bytes.
    Raises ValueError with a user-facing message when the response is an
    HTML page (login redirect / error page) instead of a spreadsheet."""
    import urllib.request

    cookie_header = "; ".join(
        "{}={}".format(c.get("name"), c.get("value"))
        for c in driver.get_cookies() if c.get("name"))
    req = urllib.request.Request(url, headers={
        "Cookie": cookie_header,
        "User-Agent": "DC-Admin-Suite BatchReviseManager",
    })
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        data = resp.read()

    if not data:
        raise ValueError("Empty response from the server.")
    head = data[:4096].lstrip().lower()
    if head.startswith(b"<!doctype") or head.startswith(b"<html") \
            or b"<html" in head[:512]:
        if b'name="password"' in head and b'name="login"' in head:
            raise ValueError("LOGIN")
        raise ValueError("Server returned a web page instead of a "
                         "spreadsheet (report may have been deleted).")
    return data


# ---------------------------------------------------------------------------
# Hierarchy model — identical semantics to the Structure Regenerator's, so
# the two modules scope structures the same way.
# ---------------------------------------------------------------------------
def build_model(rows, source: str) -> dict:
    if not rows:
        raise ValueError("The hierarchy contains no structures.")

    root = rows[0][2][0]
    types, levels, chains = {}, {}, []
    for ctx, type_label, chain in rows:
        chains.append(chain)
        types[ctx] = type_label
        for i, node in enumerate(chain):
            if i == 0:
                continue                      # skip the root
            levels[node] = max(levels.get(node, 0), i + 1)
            types.setdefault(node, "")

    desc_sets = {}
    for chain in chains:
        for i in range(1, len(chain)):
            bucket = desc_sets.setdefault(chain[i], set())
            for j in range(i + 1, len(chain)):
                bucket.add(chain[j])
    desc_count = {ctx: len(desc_sets.get(ctx, ())) for ctx in levels}

    return {"root": root, "chains": chains, "levels": levels,
            "types": types, "desc_count": desc_count, "source": source}


def resolve_targets(model: dict, mode: str, parents) -> set:
    """mode "all" → every node; mode "selected" → each chosen parent plus
    every structure beneath it in any chain (chain membership)."""
    if mode == "all":
        return set(model["levels"])
    chosen = {p for p in parents if p in model["levels"]}
    targets = set()
    for chain in model["chains"]:
        for i in range(1, len(chain)):
            if chain[i] in chosen:
                targets.update(chain[i:])
                break
    return targets


def split_targets(model: dict, targets):
    """Split scope into (generate, excluded_communities, excluded_unknown).
    Communities/Events have no batch revise page; chain-only intermediates
    (type "", never seen on the showall listing) are almost certainly
    communities too, so they are excluded rather than error out mid-run."""
    generate, comm, unknown = [], [], []
    for ctx in sorted(targets):
        label = model["types"].get(ctx, "")
        if label in EXCLUDED_TYPE_LABELS:
            comm.append(ctx)
        elif not label:
            unknown.append(ctx)
        else:
            generate.append(ctx)
    return generate, comm, unknown


# ---------------------------------------------------------------------------
# Hierarchy report parsing (input) — same format as the Hierarchy Mapping
# Tool / Structure Regenerator: one sheet, Context ID | Type | Level1…LevelN.
# ---------------------------------------------------------------------------
def parse_report(path: str):
    from openpyxl import load_workbook

    try:
        wb = load_workbook(path, read_only=True, data_only=True)
    except Exception as e:
        raise ValueError("Couldn't open the workbook ({})."
                         .format(e.__class__.__name__))
    try:
        ws = wb["Hierarchy"] if "Hierarchy" in wb.sheetnames else wb.active
        rows_iter = ws.iter_rows(values_only=True)
        header = next(rows_iter, None)
        if (not header or len(header) < 3
                or not str(header[0] or "").lower().startswith("context")
                or not str(header[2] or "").lower().startswith("level")):
            raise ValueError(
                "That workbook doesn't look like a hierarchy report "
                "(expected headers: Context ID | Type | Level1…).")

        rows = []
        for raw in rows_iter:
            if not raw:
                continue
            ctx = str(raw[0] or "").strip()
            if not ctx:
                continue
            type_label = str(raw[1] or "").strip() if len(raw) > 1 else ""
            chain = [str(c).strip() for c in raw[2:]
                     if c is not None and str(c).strip()]
            if len(chain) < 2:                 # need at least root + itself
                continue
            rows.append((ctx, type_label, chain))
    finally:
        wb.close()

    if not rows:
        raise ValueError("No structure rows found in that report.")
    return rows


# ---------------------------------------------------------------------------
# Queue workbook parsing (input to the Download workflow) — written by this
# module's Generate run. Columns are located by header name so a future
# version can add columns without breaking older queues.
# ---------------------------------------------------------------------------
def parse_queue(path: str):
    """Return queue rows [{"ctx","type","epoch","url"}, ...] (Requested rows
    only). Raises ValueError with a user-facing message on any problem."""
    from openpyxl import load_workbook

    try:
        wb = load_workbook(path, read_only=True, data_only=True)
    except Exception as e:
        raise ValueError("Couldn't open the workbook ({})."
                         .format(e.__class__.__name__))
    try:
        ws = wb[QUEUE_SHEET] if QUEUE_SHEET in wb.sheetnames else wb.active
        rows_iter = ws.iter_rows(values_only=True)
        header = [str(h or "").strip().lower()
                  for h in (next(rows_iter, None) or ())]

        def col(name):
            return header.index(name) if name in header else -1

        c_ctx = col("context id")
        c_type = col("type")
        c_status = col("status")
        c_epoch = col("generate epoch")
        c_url = col("batch revise url")
        if c_ctx < 0 or c_epoch < 0:
            raise ValueError(
                "That workbook doesn't look like a batch revise queue "
                "(expected headers incl. Context ID and Generate Epoch).")

        def cell(raw, idx):
            return str(raw[idx] or "").strip() \
                if 0 <= idx < len(raw) and raw[idx] is not None else ""

        rows = []
        for raw in rows_iter:
            if not raw:
                continue
            ctx = cell(raw, c_ctx)
            if not ctx:
                continue
            status = cell(raw, c_status)
            if status and not status.lower().startswith("requested"):
                continue                       # skipped/failed rows
            try:
                epoch = int(float(cell(raw, c_epoch)))
            except ValueError:
                continue
            rows.append({"ctx": ctx, "type": cell(raw, c_type),
                         "epoch": epoch, "url": cell(raw, c_url)})
    finally:
        wb.close()

    if not rows:
        raise ValueError("No requested structures found in that queue.")
    return rows


def scan_reports(folder: str, pattern: str):
    """List matching workbooks in `folder`, newest first."""
    hits = []
    for p in glob.glob(os.path.join(folder, pattern)):
        try:
            mtime = os.path.getmtime(p)
        except OSError:
            continue
        hits.append({"name": os.path.basename(p), "path": p,
                     "modified": time.strftime("%Y-%m-%d %H:%M",
                                               time.localtime(mtime)),
                     "_m": mtime})
    hits.sort(key=lambda h: h["_m"], reverse=True)
    for h in hits:
        del h["_m"]
    return hits[:25]


