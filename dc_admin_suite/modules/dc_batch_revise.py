XLSX_MIME = ("application/vnd.openxmlformats-officedocument"
             ".spreadsheetml.sheet")

_LOCAL_HOSTS = ("127.0.0.1", "localhost", "::1", "[::1]", "")


def request_allowed(handler) -> bool:
    """Reject requests that did not originate locally (DNS rebinding /
    cross-site form/fetch guard — see the module template)."""
    host = (handler.headers.get("Host") or "").rsplit(":", 1)[0].lower()
    if host not in _LOCAL_HOSTS:
        return False
    origin = handler.headers.get("Origin")
    if origin:
        if origin.lower() == "null":     # sandboxed/file: pages - reject
            return False
        if (urlparse(origin).hostname or "").lower() not in _LOCAL_HOSTS:
            return False
    return True


def make_handler(session: dict, page: bytes):
    class Handler(BaseHTTPRequestHandler):
        def _json(self, obj, code=200):
            body = json.dumps(obj).encode("utf-8")
            self.send_response(code)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def _body(self):
            length = int(self.headers.get("Content-Length", 0))
            return json.loads(self.rfile.read(length)) if length else {}

        def _running(self):
            with LOCK:
                return STATE["phase"] in RUNNING_PHASES

        def _send_file(self, path):
            if not path or not os.path.isfile(path):
                return self._json({"error": "No file available."}, 404)
            data = Path(path).read_bytes()
            self.send_response(200)
            self.send_header("Content-Type", XLSX_MIME)
            self.send_header("Content-Disposition",
                             'attachment; filename="{}"'
                             .format(os.path.basename(path)))
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self):
            if not request_allowed(self):
                return self._json({"error": "Forbidden (non-local request)."}, 403)
            if self.path == "/api/log":
                return send_run_log(self)
            if self.path == "/api/state":
                with LOCK:
                    return self._json(dict(STATE))
            if self.path == "/api/hierarchy":
                with LOCK:
                    model = MODEL
                if model is None:
                    return self._json({"nodes": []})
                nodes = [{"ctx": ctx,
                          "type": model["types"].get(ctx, ""),
                          "level": model["levels"][ctx],
                          "desc": model["desc_count"].get(ctx, 0)}
                         for ctx in sorted(model["levels"])]
                return self._json({"root": model["root"], "nodes": nodes})
            if self.path == "/download":
                with LOCK:
                    path = STATE["last_file"]
                return self._send_file(path)
            if self.path == "/download-report":
                with LOCK:
                    path = STATE["report_file"]
                return self._send_file(path)
            # default: the app page
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(page)))
            self.end_headers()
            self.wfile.write(page)

        def do_POST(self):
            if not request_allowed(self):
                return self._json({"error": "Forbidden (non-local request)."}, 403)
            if self.path == "/api/clear":
                with LOCK:
                    busy = STATE["phase"] in RUNNING_PHASES
                if busy:
                    return self._json({"error": CLEAR_REFUSED}, 409)
                clear_for_new_run()
                return self._json({"ok": True})
            if self.path == "/api/reports/scan":
                try:
                    req = self._body()
                    folder = os.path.expanduser(str(req["folder"]).strip())
                    kind = str(req.get("kind", "hier"))
                except (KeyError, ValueError, json.JSONDecodeError):
                    return self._json({"error": "Bad request."}, 400)
                if kind not in ("hier", "queue"):
                    return self._json({"error": "Bad request."}, 400)
                if not folder or not os.path.isdir(folder):
                    return self._json(
                        {"error": "Folder does not exist: " + folder}, 400)
                pattern = HIER_GLOB if kind == "hier" else QUEUE_GLOB
                return self._json({"reports": scan_reports(folder, pattern)})

            if self.path == "/api/uploads/scan":
                try:
                    folder = os.path.expanduser(
                        str(self._body()["folder"]).strip())
                except (KeyError, ValueError, json.JSONDecodeError):
                    return self._json({"error": "Bad request."}, 400)
                if not folder or not os.path.isdir(folder):
                    return self._json(
                        {"error": "Folder does not exist: " + folder}, 400)
                matched, unmatched = scan_upload_files(folder)
                return self._json({"files": matched, "unmatched": unmatched})

            if self.path == "/api/reports/load":
                if self._running():
                    return self._json({"error": "A job is running."}, 409)
                try:
                    req = self._body()
                    path = os.path.expanduser(str(req["path"]).strip())
                    kind = str(req.get("kind", "hier"))
                except (KeyError, ValueError, json.JSONDecodeError):
                    return self._json({"error": "Bad request."}, 400)
                if kind not in ("hier", "queue"):
                    return self._json({"error": "Bad request."}, 400)
                if not path or not os.path.isfile(path):
                    return self._json(
                        {"error": "File does not exist: " + path}, 400)
                try:
                    if kind == "hier":
                        rows = parse_report(path)
                        set_model(build_model(
                            rows, "loaded from " + os.path.basename(path)))
                        log("Loaded hierarchy report: " + path)
                        with LOCK:
                            return self._json({"ok": True,
                                               "hier": dict(STATE["hier"])})
                    rows = parse_queue(path)
                    set_queue(rows, "loaded from " + os.path.basename(path))
                    log("Loaded queue workbook: " + path)
                    with LOCK:
                        return self._json({"ok": True,
                                           "queue": dict(STATE["queue"])})
                except ValueError as e:
                    return self._json({"error": str(e)}, 400)

            if self.path == "/api/map":
                if self._running():
                    return self._json({"error": "A job is already running."}, 409)
                try:
                    out_dir = os.path.expanduser(
                        str(self._body()["out_dir"]).strip())
                except (KeyError, ValueError, json.JSONDecodeError):
                    return self._json({"error": "Bad request."}, 400)
                if not out_dir or not os.path.isdir(out_dir):
                    return self._json(
                        {"error": "Output folder does not exist: " + out_dir},
                        400)
                if not start_run(map_worker, (session, out_dir),
                                 events=(STOP_EVENT, PAUSE_EVENT)):
                    return self._json({"error": "A job is already running."}, 409)
                return self._json({"ok": True})

            if self.path == "/api/start":
                if self._running():
                    return self._json({"error": "A job is already running."}, 409)
                try:
                    req = self._body()
                    workflow = str(req.get("workflow", "generate"))
                    out_dir = os.path.expanduser(str(req["out_dir"]).strip())
                except (KeyError, ValueError, json.JSONDecodeError):
                    return self._json({"error": "Bad request."}, 400)
                if workflow not in ("generate", "download", "upload"):
                    return self._json({"error": "Bad request."}, 400)
                if not out_dir or not os.path.isdir(out_dir):
                    return self._json(
                        {"error": "Output folder does not exist: " + out_dir},
                        400)

                if workflow == "generate":
                    mode = str(req.get("mode", "all"))
                    parents_sel = [str(p) for p in req.get("parents", [])]
                    if mode not in ("all", "selected"):
                        return self._json({"error": "Bad request."}, 400)
                    with LOCK:
                        loaded = MODEL is not None
                    if not loaded:
                        return self._json(
                            {"error": "Load or map a hierarchy first."}, 400)
                    if mode == "selected" and not parents_sel:
                        return self._json(
                            {"error": "Check at least one parent structure."},
                            400)
                    if not start_run(generate_worker, (session, out_dir, mode, parents_sel),
                                     events=(STOP_EVENT, PAUSE_EVENT)):
                        return self._json({"error": "A job is already running."}, 409)
                    return self._json({"ok": True})

                if workflow == "upload":
                    # Re-validate server-side: every path must exist and
                    # every filename must re-parse to a context — never
                    # trust the client's mapping.
                    try:
                        paths = [str(p) for p in req.get("files", [])]
                        regen = bool(req.get("regen", False))
                    except (ValueError, TypeError):
                        return self._json({"error": "Bad request."}, 400)
                    if not paths:
                        return self._json(
                            {"error": "Check at least one file to upload."},
                            400)
                    files, bad = [], []
                    for p in paths:
                        p = os.path.expanduser(p)
                        name = os.path.basename(p)
                        info = parse_upload_name(name)
                        if not os.path.isfile(p) or info is None:
                            bad.append(name or p)
                            continue
                        files.append({"path": p, "name": name,
                                      "ctx": info["ctx"],
                                      "part": info["part"]})
                    if bad:
                        return self._json(
                            {"error": "Not uploadable (missing, or not "
                                      "named <context>_part<N>.xls): " +
                                      ", ".join(bad[:5])}, 400)
                    if not start_run(upload_worker, (session, out_dir, files, regen),
                                     events=(STOP_EVENT, PAUSE_EVENT)):
                        return self._json({"error": "A job is already running."}, 409)
                    return self._json({"ok": True})

                with LOCK:
                    loaded = QUEUE is not None
                if not loaded:
                    return self._json(
                        {"error": "Load a queue workbook first."}, 400)
                if not start_run(download_worker, (session, out_dir),
                                 events=(STOP_EVENT, PAUSE_EVENT)):
                    return self._json({"error": "A job is already running."}, 409)
                return self._json({"ok": True})

            if self.path == "/api/pause":
                if not self._running():
                    return self._json({"error": "No job is running."}, 409)
                try:
                    req = self._body()
                    want_pause = bool(req.get("paused",
                                              not PAUSE_EVENT.is_set()))
                except (ValueError, json.JSONDecodeError):
                    return self._json({"error": "Bad request."}, 400)
                if want_pause:
                    PAUSE_EVENT.set()
                    log("Job paused.")
                else:
                    PAUSE_EVENT.clear()
                    log("Job resumed.")
                set_state(paused=want_pause)
                return self._json({"ok": True, "paused": want_pause})

            if self.path == "/api/stop":
                if not self._running():
                    return self._json({"error": "No job is running."}, 409)
                STOP_EVENT.set()
                PAUSE_EVENT.clear()
                set_state(paused=False)
                log("Stop requested by user.")
                return self._json({"ok": True})

            return self._json({"error": "Not found."}, 404)

        def log_message(self, *a):
            pass

    return Handler


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=MANIFEST["name"])
    parser.add_argument("--port", type=int, default=None)
    parser.add_argument("--session", default=str(DEFAULT_SESSION))
    args = parser.parse_args()

    session = load_session(Path(args.session))
    port = args.port or free_port()
    server = ThreadingHTTPServer(("127.0.0.1", port),
                                 make_handler(session, build_page(session)))
    url = "http://127.0.0.1:{}".format(port)
    print("{} running at {}".format(MANIFEST["name"], url))
    if args.port is None:  # standalone launch → open a browser ourselves
        threading.Timer(0.6, webbrowser.open, args=(url,)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        sys.exit(0)


if __name__ == "__main__":
    main()
