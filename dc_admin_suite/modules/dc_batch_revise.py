# Worker 4: the UPLOAD run — submit each revised .xls through the structure's
# own upload form in the attached debug Chrome. Selenium is used (not a raw
# multipart POST) so the submission is exactly what the page itself performs.
# Elements are located with the string selector form ("css selector", …) to
# keep selenium imports inside attach_chrome only.
