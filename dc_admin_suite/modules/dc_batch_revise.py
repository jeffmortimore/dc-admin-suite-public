# ---------------------------------------------------------------------------
# Upload-file recognition — STRICTLY the Download workflow's naming:
# <context>_part<N>.xls, optionally <context>_<exportitem>_part<N>.xls.
# Greedy regexes anchor on the LAST "_part"/"_<digits>", so context slugs
# containing underscores (e.g. yearly publications like amtp-proceedings_2026)
# still parse correctly. Anything else is "unmatched" and never uploaded.
# ---------------------------------------------------------------------------
_UPLOAD_NAME_RE = re.compile(r"^(.+)_part(\d+)\.xls$", re.IGNORECASE)
_EPOCH_TAG_RE = re.compile(r"^(.+)_(\d{9,11})$")


def parse_upload_name(name: str):
    """Return {"ctx", "part"} for a Download-convention filename, else None."""
    m = _UPLOAD_NAME_RE.match(name)
    if not m:
        return None
    stem, part = m.group(1), int(m.group(2))
    tag = _EPOCH_TAG_RE.match(stem)
    if tag:                                  # strip the _<exportitem> tag
        stem = tag.group(1)
    ctx = stem.strip()
    if not ctx or "/" in ctx or ctx.startswith("http"):
        return None
    return {"ctx": ctx, "part": part}


def scan_upload_files(folder: str):
    """Scan `folder` (non-recursive) for revised batch revise spreadsheets.
    Returns (matched, unmatched): matched = [{"name","path","ctx","part",
    "size","modified"}, ...] sorted by (ctx, part, name); unmatched = the
    other *.xls names, so the UI can show what was skipped and why."""
    matched, unmatched = [], []
    for p in sorted(glob.glob(os.path.join(folder, "*.xls"))):
        name = os.path.basename(p)
        info = parse_upload_name(name)
        if info is None:
            unmatched.append(name)
            continue
        try:
            st = os.stat(p)
        except OSError:
            continue
        matched.append({"name": name, "path": p,
                        "ctx": info["ctx"], "part": info["part"],
                        "size": st.st_size,
                        "modified": time.strftime("%Y-%m-%d %H:%M",
                                                  time.localtime(st.st_mtime))})
    matched.sort(key=lambda f: (f["ctx"], f["part"], f["name"]))
    return matched, unmatched


